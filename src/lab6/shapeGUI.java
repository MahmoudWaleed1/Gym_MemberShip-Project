    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        String chosenShape = (String)comboBox.getSelectedItem();
        Shape[] shapes = dr.getShapes();
        for(Shape shape: shapes){
            if(chosenShape.equals(shape.getName())){
                dr.removeShape(shape);
                comboBox.remove(this);
                break;}           
        }

        canvas.clearRect(0, 0, panel1.getWidth(), panel1.getHeight());
        panel1.setBackground(Color.WHITE);
        panel1.paintAll(canvas);
        dr.refresh(canvas);
 
    }//GEN-LAST:event_deleteActionPerformed

